-- BacklogIQ Phase 2C manual-only migration. DO NOT run until the Version A schema
-- preflight below matches actual column types and policies have been reviewed.
-- Adds a child table only; no existing project or stakeholder-request data is changed.

begin;

-- Verify assumptions before creating FKs. Version A IDs are expected to be UUID.
do $$
declare
  projects_id_type text;
  requests_id_type text;
  requests_project_type text;
begin
  select data_type into projects_id_type from information_schema.columns
    where table_schema='public' and table_name='projects' and column_name='id';
  select data_type into requests_id_type from information_schema.columns
    where table_schema='public' and table_name='stakeholder_requests' and column_name='id';
  select data_type into requests_project_type from information_schema.columns
    where table_schema='public' and table_name='stakeholder_requests' and column_name='project_id';
  if projects_id_type is distinct from 'uuid'
     or requests_id_type is distinct from 'uuid'
     or requests_project_type is distinct from projects_id_type then
    raise exception 'Backlog migration expects UUID ids: projects.id=%, stakeholder_requests.id=%, stakeholder_requests.project_id=%. Inspect Version A types and adapt this migration before applying.', projects_id_type, requests_id_type, requests_project_type;
  end if;
end $$;

-- Needed by the composite FK, guarantees every request/project pair is a real pair.
-- Existing request IDs are unique, so this index preserves all existing rows.
create unique index if not exists stakeholder_requests_project_id_id_uq
  on public.stakeholder_requests(project_id, id);

create table if not exists public.backlog_items (
  id uuid primary key default gen_random_uuid(),
  project_id uuid not null references public.projects(id) on delete restrict,
  stakeholder_request_id uuid not null,
  title text not null check (char_length(btrim(title)) between 1 and 200),
  item_type text not null check (item_type in ('Epic','User Story','Bug','Technical Task','Spike')),
  priority text not null default 'Medium' check (priority in ('Critical','High','Medium','Low')),
  status text not null default 'Draft' check (status in ('Draft','Ready','In Progress','In Testing','Done')),
  acceptance_given text not null default '',
  acceptance_when text not null default '',
  acceptance_then text not null default '',
  completion_notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint backlog_items_request_same_project_fk
    foreign key (project_id, stakeholder_request_id)
    references public.stakeholder_requests(project_id, id) on delete restrict,
  constraint backlog_items_ready_criteria_check check (
    status <> 'Ready' or
    (item_type not in ('User Story','Bug') or
      (length(btrim(acceptance_given)) > 0 and length(btrim(acceptance_when)) > 0 and length(btrim(acceptance_then)) > 0))
  ),
  constraint backlog_items_ready_outcome_check check (
    status <> 'Ready' or item_type not in ('Epic','Technical Task','Spike') or
    length(btrim(completion_notes)) > 0 or
    (length(btrim(acceptance_given)) > 0 and length(btrim(acceptance_when)) > 0 and length(btrim(acceptance_then)) > 0)
  )
);

create index if not exists backlog_items_project_updated_idx
  on public.backlog_items(project_id, updated_at desc);
create index if not exists backlog_items_request_idx
  on public.backlog_items(stakeholder_request_id);

-- Timestamp is always generated by the server on an update, not client-supplied.
create or replace function public.backlogiq_touch_backlog_item_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger backlogiq_set_backlog_item_updated_at
  before update on public.backlog_items
  for each row execute function public.backlogiq_touch_backlog_item_updated_at();

alter table public.backlog_items enable row level security;
-- Explicitly start with no browser grants. RLS cannot substitute for grants.
revoke all on table public.backlog_items from public, anon, authenticated;
grant select on table public.backlog_items to authenticated;
grant insert (project_id, stakeholder_request_id, title, item_type, priority, status,
  acceptance_given, acceptance_when, acceptance_then, completion_notes)
  on table public.backlog_items to authenticated;
-- Disallow changing source linkage, IDs, and timestamps through the browser API.
grant update (title, item_type, priority, status,
  acceptance_given, acceptance_when, acceptance_then, completion_notes)
  on table public.backlog_items to authenticated;

create policy backlog_items_owner_select on public.backlog_items
  for select to authenticated using (
    exists (select 1 from public.projects p where p.id=backlog_items.project_id and p.owner_id=(select auth.uid()))
  );
create policy backlog_items_owner_insert on public.backlog_items
  for insert to authenticated with check (
    exists (select 1 from public.projects p where p.id=backlog_items.project_id and p.owner_id=(select auth.uid()))
    and exists (select 1 from public.stakeholder_requests r where r.id=backlog_items.stakeholder_request_id and r.project_id=backlog_items.project_id)
  );
create policy backlog_items_owner_update on public.backlog_items
  for update to authenticated using (
    exists (select 1 from public.projects p where p.id=backlog_items.project_id and p.owner_id=(select auth.uid()))
  ) with check (
    exists (select 1 from public.projects p where p.id=backlog_items.project_id and p.owner_id=(select auth.uid()))
    and exists (select 1 from public.stakeholder_requests r where r.id=backlog_items.stakeholder_request_id and r.project_id=backlog_items.project_id)
  );

commit;

-- Review the installed policies after manually applying this migration.
select schemaname,tablename,policyname,cmd,qual,with_check
from pg_policies where schemaname='public' and tablename='backlog_items';
